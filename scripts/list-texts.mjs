#!/usr/bin/env node
/**
 * Builds src/i18n/textCatalog.ts — the list of every piece of visitor-facing
 * text the studio can edit. Re-run it after adding or changing any wording:
 *
 *     node scripts/list-texts.mjs
 *
 * Two kinds of text are collected:
 *   1. dictionary keys (src/i18n/translations.ts) that some page really uses —
 *      found by looking for the key as a string literal anywhere else in src,
 *      which also catches keys held in arrays/objects (e.g. "shop.fresh").
 *      Keys nothing references any more are left out, so the editor never
 *      offers a field that changes nothing.
 *   2. inline pairs written as  x("English", "العربية")  inside a page.
 *
 * Studio-only wording (admin.*, gh.*, lock.*) is never offered.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const src = join(root, "src");

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : /\.(ts|tsx)$/.test(name) ? [full] : [];
  });

const files = walk(src).map((full) => ({ full, rel: relative(src, full).split(sep).join("/") }));
const STUDIO_ONLY = /^(admin|gh|lock)\./;

/* 1 ── dictionary keys */
const dictSource = readFileSync(join(src, "i18n/translations.ts"), "utf8");
const allKeys = [...dictSource.matchAll(/^  "([A-Za-z0-9.]+)": \{/gm)].map((m) => m[1]);

const consumers = files.filter(
  ({ rel }) => !rel.startsWith("i18n/") && !rel.startsWith("pages/Admin/") && rel !== "components/GitHubOAuthHandler.tsx"
);
const corpus = consumers.map(({ full }) => readFileSync(full, "utf8")).join("\n");
const dictKeys = allKeys.filter((key) => !STUDIO_ONLY.test(key) && corpus.includes(`"${key}"`));

/* 2 ── inline pairs */
const pair = /\bx\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)/g;
const unescape = (value) => JSON.parse(`"${value}"`);
const seen = new Map();
for (const { full, rel } of consumers) {
  const text = readFileSync(full, "utf8");
  for (const match of text.matchAll(pair)) {
    const en = unescape(match[1]);
    const ar = unescape(match[2]);
    // A real bilingual text has Arabic letters on the Arabic side. This keeps
    // class names and locale codes (x("en-US", "ar-EG")) out of the editor.
    if (!/[\u0600-\u06FF]/.test(ar)) continue;
    if (!seen.has(en)) seen.set(en, { en, ar, file: rel });
  }
}
const inline = [...seen.values()].sort((a, b) => a.file.localeCompare(b.file) || a.en.localeCompare(b.en));

const out = `// AUTO-GENERATED by scripts/list-texts.mjs — do not edit by hand.
// ${dictKeys.length} dictionary texts + ${inline.length} inline texts.

/** Dictionary keys that some page uses and the studio may edit. */
export const dictTextKeys: readonly string[] = ${JSON.stringify(dictKeys, null, 2)};

/** Texts written inline in a page as x("English", "العربية"). */
export const inlineTexts: readonly { en: string; ar: string; file: string }[] = ${JSON.stringify(inline, null, 2)};

const valid = new Set<string>([...dictTextKeys, ...inlineTexts.map((item) => "i:" + item.en)]);

/** True when a stored text edit still refers to a text that exists. */
export const isValidTextId = (id: string): boolean => valid.has(id);
`;
writeFileSync(join(src, "i18n/textCatalog.ts"), out);
console.log(`textCatalog.ts: ${dictKeys.length} dictionary texts (of ${allKeys.length}; ${allKeys.length - dictKeys.length} unused or studio-only), ${inline.length} inline texts`);
