#!/usr/bin/env bash
# Inline the bottle cut-outs into the JS bundle.
#
#   bash scripts/embed-bottles.sh <dir-with-webps>
#
# Why: the site ships as ONE html file (vite-plugin-singlefile). A file in
# public/ is a separate request that a single-file deployment may never serve,
# and binary files are easy to lose between machines. A generated TypeScript
# module is plain text, versioned with the code, and cannot 404.
set -euo pipefail
dir="${1:?usage: embed-bottles.sh <dir-with-webps>}"
out="src/data/bottleAssets.ts"

{
  echo "// AUTO-GENERATED by scripts/embed-bottles.sh — do not edit by hand."
  echo "// Keys are the paths products reference in their \`cutout\` field."
  echo "export const bottleAssets: Record<string, string> = {"
  for f in "$dir"/*.webp; do
    name="$(basename "$f")"
    printf '  "/images/bottles/%s": "data:image/webp;base64,%s",\n' "$name" "$(base64 -w0 "$f")"
  done
  echo "};"
} > "$out"
echo "wrote $out ($(( $(stat -c%s "$out") / 1024 )) KB, $(ls "$dir"/*.webp | wc -l) images)"
